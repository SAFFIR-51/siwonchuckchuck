/** Guidance by the number of ticked items (not a diagnosis). */
export function selfCheckResult(count: number) {
  if (count === 0) {
    return {
      title: "체크한 항목이 없어요.",
      text: "지금 해당하는 항목이 없다면 다행이에요. 불편함이 생기면 다시 확인해 보세요.",
    };
  }
  if (count <= 2) {
    return {
      title: `${count}개 항목에 해당해요.`,
      text: "가벼운 불편함이라도 계속되거나 점점 심해진다면 진료로 상태를 확인해 보세요.",
    };
  }
  return {
    title: `${count}개 항목에 해당해요.`,
    text: "여러 불편함이 함께 나타나고 있어요. 증상이 시작된 과정과 현재 상태를 진료로 확인해 보시길 권해드려요.",
  };
}
